/*
  shapes.js —— 物品形状模板（字符画）
  =====================================

  物品贴图和方块贴图是两回事：
    方块 = 满格的材质纹理（石头、木板）
    物品 = 透明背景上的一个【形状】（剑、宝石、药水瓶）

  形状这东西没法用噪点算法"长"出来，所以老实画成字符画：
    .  透明
    #  主体色
    +  高光（主体色提亮）
    -  阴影（主体色压暗）
    o  次色（剑柄、瓶盖这种，用第二个颜色）
    @  次色高光

  16×16，一个字符一个像素。好处是形状可控、可读、想加新形状照着画一张就行。
*/
