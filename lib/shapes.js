export const SHAPE_NAMES = Object.keys(SHAPES)

/** 把主体色按比例提亮/压暗 */
function shade(hex, k) {
  const [r, g, b] = hexToRgba(hex)
  const c = (v) => Math.max(0, Math.min(255, Math.round(v * k)))
  return [c(r), c(g), c(b)]
}

/**
 * 用形状模板画一张物品贴图。
 * @param shape  SHAPES 里的名字
 * @param color  主体色 #rrggbb
 * @param opts.second 次色（剑柄、瓶盖），默认由主体色压暗得到
 * @param opts.refImg 可选：给形状内部填真实贴图的花纹（比如"红宝石剑"的刃用宝石纹）
 */
export function drawShape(shape, color, opts = {}) {
  const rows = SHAPES[shape]
  if (!rows) return null

  const h = rows.length
  const w = rows[0].length
  const cv = makeCanvas(w, h)

  const [r, g, b] = hexToRgba(color)
  const [sr, sg, sb] = opts.second
    ? hexToRgba(opts.second)
    : shade(color, 0.55)

  const ref = opts.refImg || null

  for (let y = 0; y < h; y++) {
    const line = rows[y]
    for (let x = 0; x < w; x++) {
      const ch = line[x] || '.'
      if (ch === '.') continue

      if (ch === 'o') { setPx(cv, x, y, sr, sg, sb, 255); continue }
      if (ch === '@') {
        const [ar, ag, ab] = shade(opts.second || color, 1.35)
        setPx(cv, x, y, ar, ag, ab, 255); continue
      }

      /* 主体 / 高光 / 阴影 */
      let k = 1
      if (ch === '+') k = 1.35
      else if (ch === '-') k = 0.7
      else if (ch === '#') {
        /* 主体里掺一点参考贴图的花纹，免得整片死平 */
        k = ref ? 0.88 + (ref.px[((y % ref.h) * ref.w + (x % ref.w)) * 4] / 255) * 0.24 : 1
      }
      const c = (v) => Math.max(0, Math.min(255, Math.round(v * k)))
      setPx(cv, x, y, c(r), c(g), c(b), 255)
    }
  }
  return cv
}

